"""Read-only Stage4 model evaluation and interpretation section for the EDA app."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
import streamlit as st


REPO_ROOT = Path(__file__).resolve().parents[2]
STAGE4_REPORT_ROOT = REPO_ROOT / "reports" / "stage4"

REQUIRED_REPORTS = {
    "metrics": ("model_evaluation", "final_model_performance_comparison.csv"),
    "threshold": ("model_evaluation", "test_threshold_sensitivity.csv"),
    "confusion": ("model_evaluation", "test_confusion_matrices.csv"),
    "segments": ("model_interpretability", "cold_start_long_tail_analysis.csv"),
    "importance": ("model_interpretability", "shap_feature_importance.csv"),
    "direction": ("model_interpretability", "feature_direction_analysis.csv"),
    "errors": ("model_interpretability", "error_sample_summary.csv"),
    "false_positive": ("model_interpretability", "false_positive_samples.csv"),
    "false_negative": ("model_interpretability", "false_negative_samples.csv"),
}


def _model_label(value: str) -> str:
    """Convert persisted candidate IDs into concise dashboard labels."""

    labels = {
        "baseline__xgboost": "Baseline XGBoost",
        "undersampled__lightgbm": "Undersampled LightGBM",
        "undersampled__random_forest": "Undersampled Random Forest",
        "stacking_logistic_regression": "Stacking Logistic Regression",
    }
    return labels.get(value, value.replace("__", " · ").replace("_", " ").title())


def read_model_dashboard_outputs(report_root: str | Path = STAGE4_REPORT_ROOT) -> dict[str, Any]:
    """Load only Stage4 result files already generated by the offline pipeline."""

    root = Path(report_root).expanduser().resolve()
    paths = {name: root / folder / filename for name, (folder, filename) in REQUIRED_REPORTS.items()}
    missing = [str(path) for path in paths.values() if not path.is_file()]
    if missing:
        raise FileNotFoundError("Missing Stage4 dashboard outputs: " + ", ".join(missing))
    data = {name: pd.read_csv(path) for name, path in paths.items()}
    data["images"] = {
        "roc": root / "model_evaluation" / "test_roc_curves.png",
        "pr": root / "model_evaluation" / "test_pr_curves.png",
        "confusion": root / "model_evaluation" / "test_confusion_matrices.png",
        "shap": root / "model_interpretability" / "shap_feature_importance_top10.png",
    }
    summary_path = root / "model_interpretability" / "model_interpretability_summary.json"
    data["interpretability_summary"] = json.loads(summary_path.read_text(encoding="utf-8")) if summary_path.is_file() else {}
    return data


@st.cache_data(show_spinner=False)
def load_model_dashboard_outputs(report_root: str = str(STAGE4_REPORT_ROOT)) -> dict[str, Any]:
    """Cache the small, precomputed Stage4 report files used by the dashboard."""

    return read_model_dashboard_outputs(report_root)


def build_performance_figure(metrics: pd.DataFrame, metric: str, split: str) -> go.Figure:
    """Build a multi-model comparison using an existing evaluation metric."""

    view = metrics.loc[metrics["dataset_split"].eq(split)].copy()
    view["model"] = view["candidate"].map(_model_label)
    view = view.sort_values(metric, ascending=False)
    figure = px.bar(view, x="model", y=metric, color="model", text_auto=".4f")
    figure.update_layout(showlegend=False, xaxis_title=None, yaxis_title=metric.replace("_", " ").title(), margin=dict(l=10, r=10, t=30, b=10))
    return figure


def build_threshold_figure(threshold: pd.DataFrame, candidate: str) -> go.Figure:
    """Build threshold sensitivity curves from Issue3's fixed output grid."""

    view = threshold.loc[threshold["candidate"].eq(candidate)].copy()
    figure = go.Figure()
    for metric, color in (("precision", "#60a5fa"), ("recall", "#f59e0b"), ("f1", "#34d399")):
        figure.add_trace(go.Scatter(x=view["threshold"], y=view[metric], mode="lines+markers", name=metric.title(), line=dict(color=color)))
    figure.update_layout(xaxis_title="Decision threshold", yaxis_title="Metric", margin=dict(l=10, r=10, t=30, b=10), legend_title=None)
    return figure


def build_segment_figure(segments: pd.DataFrame) -> go.Figure:
    """Build fixed-threshold performance comparisons for model-boundary segments."""

    view = segments.loc[~segments["segment"].eq("all_test_samples")].copy()
    figure = px.bar(view, x="segment", y=["precision", "recall", "f1"], barmode="group")
    figure.update_layout(xaxis_title=None, yaxis_title="Metric", legend_title=None, margin=dict(l=10, r=10, t=30, b=10))
    return figure


def build_feature_figure(importance: pd.DataFrame) -> go.Figure:
    """Build a SHAP global-importance Top10 chart from persisted results."""

    view = importance.head(10).sort_values("mean_abs_shap")
    figure = px.bar(view, x="mean_abs_shap", y="feature", orientation="h", text_auto=".3f", color_discrete_sequence=["#8b5cf6"])
    figure.update_layout(xaxis_title="Mean absolute SHAP value", yaxis_title=None, showlegend=False, margin=dict(l=10, r=10, t=30, b=10))
    return figure


def _render_metric_cards(metrics: pd.DataFrame) -> None:
    """Render core test metrics for the validation-selected leading candidate."""

    test = metrics.loc[metrics["dataset_split"].eq("test")]
    # This candidate was chosen upstream from validation results (Issue2.5).
    # Do not rank the test-set rows here: the dashboard is display-only.
    leader_rows = test.loc[test["candidate"].eq("baseline__xgboost")]
    leader = leader_rows.iloc[0] if not leader_rows.empty else test.iloc[0]
    st.caption(f"Validation-selected leading candidate: {_model_label(str(leader['candidate']))}")
    columns = st.columns(4)
    for column, label, key in zip(columns, ("Test AUC", "Average Precision", "F1 at 0.50", "LogLoss"), ("auc", "average_precision", "f1", "logloss")):
        column.metric(label, f"{float(leader[key]):.4f}")


def render_model_dashboard(report_root: str | Path = STAGE4_REPORT_ROOT) -> None:
    """Render the Stage4 Model Evaluation & Interpretation section in the existing app."""

    st.divider()
    st.markdown('<div id="model-evaluation"></div>', unsafe_allow_html=True)
    st.header("Model Evaluation & Interpretation")
    st.caption("Read-only view of precomputed Stage4 outputs. No model training or feature engineering runs in this dashboard.")
    try:
        data = load_model_dashboard_outputs(str(report_root))
    except FileNotFoundError as error:
        st.warning(str(error))
        st.info("Run Stage4 Issue2, Issue2.5, Issue3 and Issue4 locally before opening this section.")
        return

    metrics = data["metrics"]
    _render_metric_cards(metrics)
    st.subheader("Multi-model performance")
    compare_col, setting_col = st.columns([4, 1])
    with setting_col:
        split = st.selectbox("Split", ["test", "validation"], index=0, key="model_metric_split")
        metric = st.selectbox("Metric", ["auc", "average_precision", "f1", "precision", "recall", "logloss"], key="model_metric_name")
    with compare_col:
        st.plotly_chart(build_performance_figure(metrics, metric, split), use_container_width=True, config={"displayModeBar": False})

    st.subheader("ROC, PR and confusion matrices")
    image_columns = st.columns(3)
    for column, key, label in zip(image_columns, ("roc", "pr", "confusion"), ("ROC curve", "PR curve", "Confusion matrices at threshold 0.50")):
        with column:
            image_path = data["images"][key]
            if image_path.is_file():
                st.image(str(image_path), caption=label, use_container_width=True)
            else:
                st.info(f"{label} image is unavailable.")
    st.dataframe(data["confusion"], hide_index=True, use_container_width=True)

    st.subheader("Threshold sensitivity")
    candidate = st.selectbox("Candidate", metrics.loc[metrics["dataset_split"].eq("test"), "candidate"].tolist(), format_func=_model_label, key="threshold_candidate")
    st.plotly_chart(build_threshold_figure(data["threshold"], candidate), use_container_width=True, config={"displayModeBar": False})

    st.subheader("Segment performance")
    st.caption("Cold-start users: raw historical user_event_count ≤ 1. Long-tail items: raw historical item_total_count ≤ 1.")
    st.plotly_chart(build_segment_figure(data["segments"]), use_container_width=True, config={"displayModeBar": False})
    st.dataframe(data["segments"], hide_index=True, use_container_width=True)

    st.subheader("Feature importance and explanation")
    feature_col, direction_col = st.columns([3, 2])
    with feature_col:
        st.plotly_chart(build_feature_figure(data["importance"]), use_container_width=True, config={"displayModeBar": False})
    with direction_col:
        st.dataframe(data["direction"].head(10), hide_index=True, use_container_width=True)
    shap_path = data["images"]["shap"]
    if shap_path.is_file():
        st.image(str(shap_path), caption="SHAP feature importance Top10", use_container_width=True)

    st.subheader("Error-sample analysis")
    error = data["errors"].iloc[0]
    error_columns = st.columns(4)
    for column, label, key in zip(error_columns, ("True negatives", "False positives", "False negatives", "True positives"), ("tn", "fp", "fn", "tp")):
        column.metric(label, f"{int(error[key]):,}")
    sample_tabs = st.tabs(["False positives", "False negatives"])
    with sample_tabs[0]:
        st.dataframe(data["false_positive"], hide_index=True, use_container_width=True)
    with sample_tabs[1]:
        st.dataframe(data["false_negative"], hide_index=True, use_container_width=True)

    with st.expander("Dashboard inputs and run instructions", expanded=False):
        st.markdown("The dashboard reads only the generated CSV/PNG/JSON outputs under `reports/stage4/`.")
        st.code("streamlit run dashboards/eda/app.py", language="powershell")
        st.caption("Refresh the browser after rerunning the offline Stage4 scripts. The dashboard does not retrain models or rebuild features.")
